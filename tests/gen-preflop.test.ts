/**
 * Generator (not a regular test): computes preflop equity of all 169 classes
 * against 1 and 3 random hands and writes src/engine/preflopTable.ts.
 * Run with:  GEN=1 npx vitest run tests/gen-preflop.test.ts
 */
import { it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { allClasses, combosOf } from '../src/engine/handClasses';
import { equity } from '../src/engine/equity';
import { seededRng } from '../src/engine/cards';

it.skipIf(!process.env.GEN)('generate preflop table', () => {
  const rng = seededRng(42);
  const rows = allClasses().map((cls) => {
    const combo = combosOf(cls)[0];
    const hu = equity({ hero: combo, board: [], opponents: [null], iterations: 30000, rng }).equity;
    const mw = equity({ hero: combo, board: [], opponents: [null, null, null], iterations: 30000, rng }).equity;
    // Blend: heads-up value plus multiway playability (scaled to a comparable range).
    return { cls, hu, mw, score: hu * 0.6 + mw * 1.6 * 0.4 };
  });
  rows.sort((a, b) => b.score - a.score);
  const body = rows
    .map((r) => `  ['${r.cls}', ${r.hu.toFixed(3)}, ${r.mw.toFixed(3)}],`)
    .join('\n');
  const src = `// Generated by tests/gen-preflop.test.ts — do not edit by hand.
// [class, equity vs 1 random hand, equity vs 3 random hands], ordered best → worst.
export const PREFLOP_DATA: [string, number, number][] = [
${body}
];
export const PREFLOP_ORDER: string[] = PREFLOP_DATA.map((r) => r[0]);
export const PREFLOP_EQUITY: Record<string, { hu: number; mw: number }> = Object.fromEntries(
  PREFLOP_DATA.map((r) => [r[0], { hu: r[1], mw: r[2] }]),
);
`;
  writeFileSync('src/engine/preflopTable.ts', src);
}, 600000);
